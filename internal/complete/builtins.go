// Builtins is the slash commands an agent of the kind carries of its own, in a sensible order; none for a kind
// nobody has listed, so an unknown kind offers nothing of Claude Code's.
func Builtins(agent string) []Command {
	table := builtins[agent]
	out := make([]Command, 0, len(table))
	for _, c := range table {
		c.Source = "builtin"
		out = append(out, c)
	}
	return out
}
